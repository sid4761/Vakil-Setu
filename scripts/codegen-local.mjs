import { readFileSync, readdirSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

// Convex 1.46's CLI requires a deployment for component codegen. This app uses
// no components; invoke its own application generator for credential-free QA.
const workspace = resolve(import.meta.dirname, "..");
const backend = resolve(workspace, "packages/backend");
const functions = resolve(backend, "convex");
const generated = resolve(functions, "_generated");
if (generated !== resolve(workspace, "packages/backend/convex/_generated")) {
  throw new Error("Refusing code generation outside the rebuild backend.");
}
const convexRoot = resolve(backend, "node_modules/convex");
const { version } = JSON.parse(readFileSync(resolve(convexRoot, "package.json"), "utf8"));
if (version !== "1.46.0") throw new Error("Review the offline generator when upgrading Convex.");
if (existsSync(resolve(functions, "convex.config.ts"))) {
  throw new Error("Components require deployment-backed Convex codegen.");
}
const templates = resolve(convexRoot, "src/cli/codegen_templates");
const { apiCodegen } = await import(resolve(templates, "api.ts"));
const { serverCodegen } = await import(resolve(templates, "server.ts"));
function modules(directory, prefix = "") {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith("_") || entry.name.startsWith(".")) return [];
    const name = `${prefix}${entry.name}`;
    if (entry.isDirectory()) return modules(resolve(directory, entry.name), `${name}/`);
    if (!entry.name.endsWith(".ts") || entry.name.endsWith(".d.ts") || ["schema.ts", "auth.config.ts"].includes(entry.name)) return [];
    return [name];
  });
}
const api = apiCodegen(modules(functions).sort());
const server = serverCodegen({ useTypeScript: false, envVars: undefined });
// Equivalent to Convex's dynamic data model template; types derive from schema.
// Importing that template also loads deployment-only CLI dependencies.
const dataModel = `/* Generated by scripts/codegen-local.mjs. Hosted convex dev replaces this file. */
import type { DataModelFromSchemaDefinition, DocumentByName, TableNamesInDataModel, SystemTableNames } from "convex/server";
import type { GenericId } from "convex/values";
import schema from "../schema.js";
export type DataModel = DataModelFromSchemaDefinition<typeof schema>;
export type TableNames = TableNamesInDataModel<DataModel>;
export type Doc<TableName extends TableNames> = DocumentByName<DataModel, TableName>;
export type Id<TableName extends TableNames | SystemTableNames> = GenericId<TableName>;
`;
mkdirSync(generated, { recursive: true });
for (const [name, content] of Object.entries({
  "dataModel.d.ts": dataModel,
  "server.d.ts": server.DTS, "server.js": server.JS,
  "api.d.ts": api.DTS, "api.js": api.JS,
})) {
  if (typeof content !== "string") throw new Error(`Missing Convex template: ${name}`);
  writeFileSync(resolve(generated, name), content.replace(/[ \t]+$/gmu, "").trimEnd() + "\n");
}
process.stdout.write("Generated application bindings using Convex 1.46.0 templates; no deployment contacted.\n");
